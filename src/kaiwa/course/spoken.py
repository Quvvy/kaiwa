_SENTENCE = re.compile(r"[^。！？!?]+[。！？!?]*")
_END = "。！？!? "


def for_speech(text: str) -> str:
    """`text` with each sentence the course knows swapped for its kanji spelling."""
    whole = text.strip().rstrip(_END)
    if whole in SPELLING:
        return text.replace(whole, SPELLING[whole], 1)
    out = []
    for piece in _SENTENCE.findall(text):
        core = piece.strip().rstrip(_END)
        out.append(piece.replace(core, SPELLING[core], 1) if core in SPELLING else piece)
    return "".join(out) if out else text


_JP_ONLY = re.compile(r"^[ぁ-ゟ゠-ヿ、。！？ー・…～〜\s]+$")
_HAS_KANA = re.compile(r"[ぁ-ゟ゠-ヿ]")


def course_sentences() -> list[str]:
    """Every fixed Japanese sentence the course can speak, in course order, without
    its end punctuation: what SPELLING and KEEP_KANA between them must cover."""
    from kaiwa.course import build, missions, placement
    from kaiwa.course.kana import KANA_LESSONS
    from kaiwa.course.packs import PACKS
    from kaiwa.course.units import UNITS

    strings: list[str] = []

    def walk(x: object) -> None:
        if isinstance(x, dict):
            for v in x.values():
                walk(v)
        elif isinstance(x, (list, tuple)):
            for v in x:
                walk(v)
        elif isinstance(x, str) and _JP_ONLY.match(x) and _HAS_KANA.search(x):
            strings.append(x)

    walk(KANA_LESSONS)
    walk(UNITS)
    walk(PACKS)
    walk(missions.MISSIONS)
    for unit in UNITS:
        for point in unit.get("grammar", []):
            walk(build.items_for(point["id"]))
    walk(placement.BANK)
    out: list[str] = []
    seen: set[str] = set()
    for s in strings:
        for piece in _SENTENCE.findall(s):
            core = piece.strip().rstrip(_END)
            if len(core) > 1 and core not in seen:
                seen.add(core)
                out.append(core)
    return out
